; IDUMP - Intel object file dump (8086/MS-DOS)
; Machine translation of the 8080 CP/M source to 8086 MS-DOS:
;   A=AL B=CH C=CL D=DH E=DL H=BH L=BL  SP=SP, flags = 8086 flags
;   (INX/DCX/DAD wrapped in LAHF/SAHF to keep 8080 flag behaviour).
; BDOS calls map 1:1 onto MS-DOS INT 21H FCB functions (same numbers);
; the PSP (FCBs at 5CH/6CH, command tail at 80H) is copied to offset 0
; of this segment so the program sees the CP/M page-zero layout.
; Assemble: MASM file;   Link: LINK file;
;=======================================================================
CODE	SEGMENT
	ASSUME	CS:CODE,DS:CODE,ES:CODE,SS:CODE
