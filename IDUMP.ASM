DOSSTART:
	CLD				; copy PSP page to our page zero
	PUSH	CS
	POP	ES
	XOR	SI,SI
	XOR	DI,DI
	MOV	CX,128
	REP	MOVSW
	MOV	AX,CS
	MOV	DS,AX
	MOV	SS,AX
	MOV	SP,OFFSET DOSSTK
	MOV	BX,80H			; CP/M style tail: upper case, 0 terminated
	MOV	CL,[BX]
	XOR	CH,CH
	INC	BX
DT1:	JCXZ	DT3
	MOV	AL,[BX]
	CMP	AL,'a'
	JB	DT2
	CMP	AL,'z'
	JA	DT2
	SUB	AL,20H
	MOV	[BX],AL
DT2:	INC	BX
	DEC	CX
	JMP	DT1
DT3:	MOV	BYTE PTR [BX],0
	MOV	DX,80H			; default DMA
	MOV	AH,1AH
	INT	21H
	MOV	AX,OFFSET DOSEXIT	; "return to CCP"
	PUSH	AX
	JMP	YPGMSTART
DOSEXIT:
	MOV	AX,4C00H
	INT	21H
; BDOS entry: C = function, DE = parameter
BDOSF:	PUSH	BX
	PUSH	CX
	PUSH	DX
	PUSH	SI
	MOV	AH,CL
	INT	21H
	CMP	CL,14H			; read sequential: partial last record
	JNE	BF1			; (AL=3, zero filled) counts as data
	CMP	AL,3
	JNE	BF1
	XOR	AL,AL
BF1:	POP	SI
	POP	DX
	POP	CX
	POP	BX
	OR	AL,AL
	RET
